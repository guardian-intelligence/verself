func TestLoadPlanMapsAmbiguousOwnerRuntimeSecretWithExplicitJobID(t *testing.T) {
	root := t.TempDir()
	writeFile(t, root, "src/infrastructure-components/electric/containerd.nomad.hcl", `job "electric-containerd" {}`)
	writeFile(t, root, "src/infrastructure-components/electric/nomad.hcl", `job "electric" {}`)
	writeFile(t, root, "src/infrastructure-components/electric/deploy/runtime-secrets.yml", `
openbao_runtime_secret_seed_declarations:
  - name: electric.pg.password
    job_id: electric
    generated:
      bytes: 32
`)

	plan, err := LoadPlan(root, "gamma", []Component{
		{
			Component: "electric",
			JobID:     "electric-containerd",
			JobSpec:   "src/infrastructure-components/electric/containerd.nomad.hcl",
		},
		{
			Component: "electric",
			JobID:     "electric",
			JobSpec:   "src/infrastructure-components/electric/nomad.hcl",
		},
	})
	if err != nil {
		t.Fatal(err)
	}
	if len(plan.Secrets) != 1 {
		t.Fatalf("len(secrets) = %d, want 1", len(plan.Secrets))
	}
	if plan.Secrets[0].JobID != "electric" {
		t.Fatalf("secret JobID = %q, want electric", plan.Secrets[0].JobID)
	}
	if plan.Secrets[0].Generated.Bytes != 32 {
		t.Fatalf("generated bytes = %d, want 32", plan.Secrets[0].Generated.Bytes)
	}
}

func writeFile(t *testing.T, root, rel, body string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}
