func TestLoadPlanMapsOwnerLocalSecretsToNomadRoles(t *testing.T) {
	root := t.TempDir()
	writeFile(t, root, "src/services/billing-service/nomad.hcl", `job "billing" {}`)
	writeFile(t, root, "src/services/billing-service/deploy/runtime-secrets.yml", `
openbao_runtime_secret_seed_declarations:
  - name: billing-service.stripe.secret_key
    site_secret: stripe_secret_key
  - name: billing-service.stripe.webhook_secret
    site_secret: stripe_webhook_secret
`)

	plan, err := LoadPlan(root, "gamma", []Component{{
		Component: "billing",
		JobID:     "billing",
		JobSpec:   "src/services/billing-service/nomad.hcl",
	}})
	if err != nil {
		t.Fatal(err)
	}
	if len(plan.Secrets) != 2 {
		t.Fatalf("len(secrets) = %d, want 2", len(plan.Secrets))
	}
	if len(plan.NomadRoles) != 1 {
		t.Fatalf("len(roles) = %d, want 1", len(plan.NomadRoles))
	}
	role := plan.NomadRoles[0]
	if role.Name != "billing-runtime" {
		t.Fatalf("role name = %q", role.Name)
	}
	if role.Policy != "nomad-runtime-billing" {
		t.Fatalf("policy name = %q", role.Policy)
	}
	if role.Secrets[0] != "billing-service.stripe.secret_key" || role.Secrets[1] != "billing-service.stripe.webhook_secret" {
		t.Fatalf("role secrets = %#v", role.Secrets)
	}
}

