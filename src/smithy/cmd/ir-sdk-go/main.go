package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strings"
	"unicode"
)

type contractIR struct {
	IRVersion  string               `json:"irVersion"`
	Package    string               `json:"package"`
	Projection string               `json:"projection"`
	Service    serviceSpec          `json:"service"`
	Shapes     map[string]shapeSpec `json:"shapes"`
	Operations []operationSpec      `json:"operations"`
	Problems   []problemSpec        `json:"problems"`
}

type serviceSpec struct {
	Name    string             `json:"name"`
	Runtime serviceRuntimeSpec `json:"runtime"`
}

type serviceRuntimeSpec struct {
	ServiceName string `json:"serviceName"`
}

type shapeSpec struct {
	Kind        string          `json:"kind"`
	Name        string          `json:"name"`
	Sensitive   bool            `json:"sensitive"`
	Input       bool            `json:"input"`
	Output      bool            `json:"output"`
	Members     []memberSpec    `json:"members"`
	Member      *listMemberSpec `json:"member"`
	Enum        []enumValueSpec `json:"enum"`
	Constraints constraintsSpec `json:"constraints"`
}

type constraintsSpec struct {
	Length  boundSpec `json:"length"`
	Range   boundSpec `json:"range"`
	Pattern string    `json:"pattern"`
}

type boundSpec struct {
	Min *int `json:"min"`
	Max *int `json:"max"`
}

type memberSpec struct {
	Name             string           `json:"name"`
	Target           string           `json:"target"`
	JSONName         string           `json:"jsonName"`
	Required         bool             `json:"required"`
	HTTPBinding      *httpBindingSpec `json:"httpBinding"`
	NestedProperties bool             `json:"nestedProperties"`
	IdempotencyToken bool             `json:"idempotencyToken"`
}

type listMemberSpec struct {
	Target string `json:"target"`
}

type enumValueSpec struct {
	Name  string `json:"name"`
	Value string `json:"value"`
}

type httpBindingSpec struct {
	Location string `json:"location"`
	Name     string `json:"name"`
}

type operationSpec struct {
	Name        string       `json:"name"`
	OperationID string       `json:"operationId"`
	HTTP        httpSpec     `json:"http"`
	Input       string       `json:"input"`
	Output      string       `json:"output"`
	Errors      []string     `json:"errors"`
	Bindings    bindingsSpec `json:"bindings"`
}

type httpSpec struct {
	Method        string `json:"method"`
	Path          string `json:"path"`
	SuccessStatus int    `json:"successStatus"`
}

type bindingsSpec struct {
	Labels          []bindingSpec `json:"labels"`
	Headers         []bindingSpec `json:"headers"`
	Queries         []bindingSpec `json:"queries"`
	DocumentMembers []string      `json:"documentMembers"`
}

type bindingSpec struct {
	Member string `json:"member"`
	Name   string `json:"name"`
}

type problemSpec struct {
	ShapeID string `json:"shapeId"`
	Name    string `json:"name"`
	Type    string `json:"type"`
	Code    string `json:"code"`
	Status  int    `json:"status"`
}

type generator struct {
	ir      contractIR
	pkg     string
	imports map[string]bool
}

func main() {
	var irPath string
	var outPath string
	var packageName string
	flag.StringVar(&irPath, "ir", "", "Verself contract IR JSON")
	flag.StringVar(&outPath, "out", "", "generated Go file")
	flag.StringVar(&packageName, "package", "", "generated Go package name")
	flag.Parse()

	if strings.TrimSpace(irPath) == "" || strings.TrimSpace(outPath) == "" || strings.TrimSpace(packageName) == "" {
		fail(errors.New("-ir, -out, and -package are required"))
	}
	ir, err := readIR(irPath)
	if err != nil {
		fail(err)
	}
	if len(ir.Operations) == 0 {
		fail(errors.New("IR has no operations"))
	}
	g := generator{ir: ir, pkg: packageName, imports: map[string]bool{}}
	data, err := g.generate()
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(outPath, data, 0o644); err != nil {
		fail(err)
	}
}

func readIR(path string) (contractIR, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return contractIR{}, err
	}
	var ir contractIR
	if err := json.Unmarshal(data, &ir); err != nil {
		return contractIR{}, err
	}
	for id, shape := range ir.Shapes {
		if strings.TrimSpace(shape.Name) == "" {
			return contractIR{}, fmt.Errorf("shape %s has no name", id)
		}
	}
	return ir, nil
}

func (g generator) generate() ([]byte, error) {
	var body bytes.Buffer
	g.writePrelude(&body)
	g.writeScalarAliases(&body)
	g.writeEnums(&body)
	g.writeLists(&body)
	g.writeStructures(&body)
	g.writeOperationTypes(&body)
	g.writeClient(&body)
	g.writeOperationMethods(&body)
	g.writeResponseParsers(&body)
	g.writeHelpers(&body)

	var out bytes.Buffer
	out.WriteString("// Code generated by //src/smithy/cmd/ir-sdk-go. DO NOT EDIT.\n")
	out.WriteString("\n")
	out.WriteString("package ")
	out.WriteString(g.pkg)
	out.WriteString("\n\n")
	g.writeImports(&out)
	out.Write(body.Bytes())

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w\n%s", err, out.String())
	}
	return formatted, nil
}

func (g generator) writePrelude(out *bytes.Buffer) {
	fmt.Fprintf(out, "const ServiceName = %q\n\n", g.serviceName())
}

func (g generator) writeImports(out *bytes.Buffer) {
	imports := make([]string, 0, len(g.imports))
	for path := range g.imports {
		imports = append(imports, path)
	}
	sort.Strings(imports)
	if len(imports) == 0 {
		return
	}
	out.WriteString("import (\n")
	for _, path := range imports {
		fmt.Fprintf(out, "\t%q\n", path)
	}
	out.WriteString(")\n\n")
}

func (g generator) writeScalarAliases(out *bytes.Buffer) {
	ids := g.sortedShapeIDs()
	for _, id := range ids {
		shape := g.ir.Shapes[id]
		switch shape.Kind {
		case "string":
			fmt.Fprintf(out, "type %s = string\n\n", shape.Name)
		case "integer", "long":
			fmt.Fprintf(out, "type %s = int64\n\n", shape.Name)
		case "boolean":
			fmt.Fprintf(out, "type %s = bool\n\n", shape.Name)
		}
	}
}

func (g generator) writeEnums(out *bytes.Buffer) {
	for _, id := range g.sortedShapeIDs() {
		shape := g.ir.Shapes[id]
		if shape.Kind != "enum" {
			continue
		}
		fmt.Fprintf(out, "type %s string\n\n", shape.Name)
		out.WriteString("const (\n")
		values := append([]enumValueSpec(nil), shape.Enum...)
		sort.Slice(values, func(i, j int) bool { return values[i].Name < values[j].Name })
		for _, value := range values {
			fmt.Fprintf(out, "\t%s%s %s = %q\n", shape.Name, exportedIdentifier(value.Name), shape.Name, value.Value)
		}
		out.WriteString(")\n\n")
	}
}

func (g generator) writeLists(out *bytes.Buffer) {
	for _, id := range g.sortedShapeIDs() {
		shape := g.ir.Shapes[id]
		if shape.Kind != "list" || shape.Member == nil {
			continue
		}
		fmt.Fprintf(out, "type %s []%s\n\n", shape.Name, g.goType(shape.Member.Target, false))
	}
}

func (g generator) writeStructures(out *bytes.Buffer) {
	for _, id := range g.sortedShapeIDs() {
		shape := g.ir.Shapes[id]
		if shape.Kind != "structure" || shape.Input {
			continue
		}
		if shape.Output && g.outputFlattens(id) {
			continue
		}
		typeName := shape.Name
		if shape.Output {
			typeName = shape.Name + "Body"
		}
		g.writeStruct(out, typeName, shape.Members, nil)
	}
}

func (g generator) writeOperationTypes(out *bytes.Buffer) {
	ops := g.sortedOperations()
	for _, op := range ops {
		input, ok := g.ir.Shapes[op.Input]
		if !ok {
			continue
		}
		requestFields := make([]memberSpec, 0, len(input.Members))
		bodyFields := make([]memberSpec, 0, len(input.Members))
		for _, member := range input.Members {
			if isDocumentMember(member) {
				bodyFields = append(bodyFields, member)
			} else {
				requestFields = append(requestFields, member)
			}
		}
		if len(bodyFields) > 0 {
			g.writeStruct(out, input.Name+"Body", bodyFields, nil)
			bodyMember := memberSpec{Name: "body", Target: input.Name + "Body", JSONName: "body", Required: true}
			requestFields = append(requestFields, bodyMember)
		}
		g.writeStruct(out, op.Name+"Request", requestFields, map[string]string{"body": input.Name + "Body"})
		fmt.Fprintf(out, "type %sResponse struct {\n", op.Name)
		out.WriteString("\tStatusCode int\n")
		out.WriteString("\tBody []byte\n")
		fmt.Fprintf(out, "\tResult *%s\n", g.successType(op))
		out.WriteString("\tProblem *ErrorModel\n")
		out.WriteString("\tHTTPResponse *http.Response\n")
		out.WriteString("}\n\n")
		g.imports["net/http"] = true
	}
}

func (g generator) writeStruct(out *bytes.Buffer, name string, members []memberSpec, overrideTypes map[string]string) {
	fmt.Fprintf(out, "type %s struct {\n", name)
	for _, member := range members {
		fieldName := exportedIdentifier(member.Name)
		fieldType, ok := overrideTypes[member.Name]
		if !ok {
			fieldType = g.goType(member.Target, !member.Required)
		}
		tag := ""
		if member.JSONName != "" && isDocumentMember(member) {
			tagName := member.JSONName
			if !member.Required {
				tagName += ",omitempty"
			}
			tag = fmt.Sprintf(" `json:%q`", tagName)
		}
		fmt.Fprintf(out, "\t%s %s%s\n", fieldName, fieldType, tag)
	}
	out.WriteString("}\n\n")
}

func (g generator) writeClient(out *bytes.Buffer) {
	out.WriteString("type RequestEditorFn func(ctx context.Context, req *http.Request) error\n\n")
	out.WriteString("type HTTPRequestDoer interface {\n\tDo(req *http.Request) (*http.Response, error)\n}\n\n")
	out.WriteString("type ClientOption func(*Client)\n\n")
	out.WriteString("type Client struct {\n")
	out.WriteString("\tserver string\n")
	out.WriteString("\tclient HTTPRequestDoer\n")
	out.WriteString("\trequestEditors []RequestEditorFn\n")
	out.WriteString("}\n\n")
	out.WriteString("func NewClient(server string, opts ...ClientOption) (*Client, error) {\n")
	out.WriteString("\tserver = strings.TrimRight(strings.TrimSpace(server), \"/\")\n")
	out.WriteString("\tif server == \"\" {\n\t\treturn nil, fmt.Errorf(\"%s SDK transport: server URL is required\", ServiceName)\n\t}\n")
	out.WriteString("\tclient := &Client{server: server, client: http.DefaultClient}\n")
	out.WriteString("\tfor _, opt := range opts {\n\t\topt(client)\n\t}\n")
	out.WriteString("\tif client.client == nil {\n\t\treturn nil, fmt.Errorf(\"%s SDK transport: HTTP client is required\", ServiceName)\n\t}\n")
	out.WriteString("\treturn client, nil\n")
	out.WriteString("}\n\n")
	out.WriteString("func WithHTTPClient(client HTTPRequestDoer) ClientOption {\n")
	out.WriteString("\treturn func(c *Client) { c.client = client }\n")
	out.WriteString("}\n\n")
	out.WriteString("func WithRequestEditorFn(editor RequestEditorFn) ClientOption {\n")
	out.WriteString("\treturn func(c *Client) {\n\t\tif editor != nil {\n\t\t\tc.requestEditors = append(c.requestEditors, editor)\n\t\t}\n\t}\n")
	out.WriteString("}\n\n")
	g.imports["context"] = true
	g.imports["fmt"] = true
	g.imports["net/http"] = true
	g.imports["strings"] = true
}

func (g generator) writeOperationMethods(out *bytes.Buffer) {
	for _, op := range g.sortedOperations() {
		fmt.Fprintf(out, "func (c *Client) %s(ctx context.Context, request %sRequest) (*%sResponse, error) {\n", op.Name, op.Name, op.Name)
		out.WriteString("\tif c == nil || c.client == nil {\n")
		out.WriteString("\t\treturn nil, fmt.Errorf(\"%s SDK transport: client is not initialized\", ServiceName)\n")
		out.WriteString("\t}\n")
		fmt.Fprintf(out, "\treq, err := c.new%sRequest(ctx, request)\n", op.Name)
		out.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		out.WriteString("\tfor _, editor := range c.requestEditors {\n\t\tif err := editor(ctx, req); err != nil {\n\t\t\treturn nil, err\n\t\t}\n\t}\n")
		out.WriteString("\tresp, err := c.client.Do(req)\n")
		out.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		fmt.Fprintf(out, "\treturn parse%sResponse(resp)\n", op.Name)
		out.WriteString("}\n\n")

		fmt.Fprintf(out, "func (c *Client) new%sRequest(ctx context.Context, request %sRequest) (*http.Request, error) {\n", op.Name, op.Name)
		fmt.Fprintf(out, "\tpath := %q\n", op.HTTP.Path)
		for _, binding := range sortedBindings(op.Bindings.Labels) {
			member := g.inputMember(op, binding.Member)
			fmt.Fprintf(out, "\tpath = strings.ReplaceAll(path, %q, url.PathEscape(fmt.Sprint(request.%s)))\n", "{"+binding.Name+"}", exportedIdentifier(member.Name))
		}
		out.WriteString("\tendpoint, err := url.Parse(c.server + path)\n")
		out.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		if len(op.Bindings.Queries) > 0 {
			out.WriteString("\tquery := endpoint.Query()\n")
			for _, binding := range sortedBindings(op.Bindings.Queries) {
				member := g.inputMember(op, binding.Member)
				field := "request." + exportedIdentifier(member.Name)
				if member.Required {
					fmt.Fprintf(out, "\tquery.Set(%q, fmt.Sprint(%s))\n", binding.Name, field)
				} else {
					fmt.Fprintf(out, "\tif %s != nil {\n\t\tquery.Set(%q, fmt.Sprint(*%s))\n\t}\n", field, binding.Name, field)
				}
			}
			out.WriteString("\tendpoint.RawQuery = query.Encode()\n")
		}
		if len(op.Bindings.DocumentMembers) > 0 {
			out.WriteString("\trequestBody, err := json.Marshal(request.Body)\n")
			out.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
			fmt.Fprintf(out, "\treq, err := http.NewRequestWithContext(ctx, %q, endpoint.String(), bytes.NewReader(requestBody))\n", op.HTTP.Method)
		} else {
			fmt.Fprintf(out, "\treq, err := http.NewRequestWithContext(ctx, %q, endpoint.String(), nil)\n", op.HTTP.Method)
		}
		out.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		out.WriteString("\treq.Header.Set(\"Accept\", \"application/json\")\n")
		if len(op.Bindings.DocumentMembers) > 0 {
			out.WriteString("\treq.Header.Set(\"Content-Type\", \"application/json\")\n")
		}
		for _, binding := range sortedBindings(op.Bindings.Headers) {
			member := g.inputMember(op, binding.Member)
			field := "request." + exportedIdentifier(member.Name)
			if member.Required {
				fmt.Fprintf(out, "\treq.Header.Set(%q, fmt.Sprint(%s))\n", binding.Name, field)
			} else {
				fmt.Fprintf(out, "\tif %s != nil {\n\t\treq.Header.Set(%q, fmt.Sprint(*%s))\n\t}\n", field, binding.Name, field)
			}
		}
		out.WriteString("\treturn req, nil\n")
		out.WriteString("}\n\n")
	}
	g.imports["bytes"] = true
	g.imports["context"] = true
	g.imports["encoding/json"] = true
	g.imports["fmt"] = true
	g.imports["net/http"] = true
	g.imports["net/url"] = true
	g.imports["strings"] = true
}

func (g generator) writeResponseParsers(out *bytes.Buffer) {
	for _, op := range g.sortedOperations() {
		fmt.Fprintf(out, "func parse%sResponse(resp *http.Response) (*%sResponse, error) {\n", op.Name, op.Name)
		out.WriteString("\tdefer resp.Body.Close()\n")
		out.WriteString("\tbody, err := io.ReadAll(resp.Body)\n")
		out.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		fmt.Fprintf(out, "\tresult := &%sResponse{StatusCode: resp.StatusCode, Body: body, HTTPResponse: resp}\n", op.Name)
		fmt.Fprintf(out, "\tif resp.StatusCode == %d {\n", op.HTTP.SuccessStatus)
		fmt.Fprintf(out, "\t\tvar decoded %s\n", g.successType(op))
		out.WriteString("\t\tif len(body) > 0 {\n")
		out.WriteString("\t\t\tif err := json.Unmarshal(body, &decoded); err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n")
		out.WriteString("\t\t}\n")
		out.WriteString("\t\tresult.Result = &decoded\n")
		out.WriteString("\t\treturn result, nil\n")
		out.WriteString("\t}\n")
		out.WriteString("\tresult.Problem = decodeProblem(body)\n")
		out.WriteString("\treturn result, nil\n")
		out.WriteString("}\n\n")
	}
	g.imports["encoding/json"] = true
	g.imports["io"] = true
	g.imports["net/http"] = true
}

func (g generator) writeHelpers(out *bytes.Buffer) {
	out.WriteString("type ErrorModel struct {\n")
	out.WriteString("\tSchema *string `json:\"$schema,omitempty\"`\n")
	out.WriteString("\tType *string `json:\"type,omitempty\"`\n")
	out.WriteString("\tTitle *string `json:\"title,omitempty\"`\n")
	out.WriteString("\tStatus *int64 `json:\"status,omitempty\"`\n")
	out.WriteString("\tDetail *string `json:\"detail,omitempty\"`\n")
	out.WriteString("\tInstance *string `json:\"instance,omitempty\"`\n")
	out.WriteString("\tCode *string `json:\"code,omitempty\"`\n")
	out.WriteString("\tRequestID *string `json:\"requestId,omitempty\"`\n")
	out.WriteString("\tTraceparent *string `json:\"traceparent,omitempty\"`\n")
	out.WriteString("\tErrors []map[string]any `json:\"errors,omitempty\"`\n")
	out.WriteString("}\n\n")
	out.WriteString("func decodeProblem(body []byte) *ErrorModel {\n")
	out.WriteString("\tif len(body) == 0 {\n\t\treturn nil\n\t}\n")
	out.WriteString("\tvar problem ErrorModel\n")
	out.WriteString("\tif err := json.Unmarshal(body, &problem); err != nil {\n\t\treturn nil\n\t}\n")
	out.WriteString("\treturn &problem\n")
	out.WriteString("}\n")
	g.imports["encoding/json"] = true
}

func (g generator) sortedShapeIDs() []string {
	ids := make([]string, 0, len(g.ir.Shapes))
	for id := range g.ir.Shapes {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool {
		left := g.ir.Shapes[ids[i]].Name
		right := g.ir.Shapes[ids[j]].Name
		if left == right {
			return ids[i] < ids[j]
		}
		return left < right
	})
	return ids
}

func (g generator) sortedOperations() []operationSpec {
	ops := append([]operationSpec(nil), g.ir.Operations...)
	sort.Slice(ops, func(i, j int) bool { return ops[i].Name < ops[j].Name })
	return ops
}

func (g generator) goType(target string, optional bool) string {
	if strings.Contains(target, "#") {
		if shape, ok := g.ir.Shapes[target]; ok {
			switch shape.Kind {
			case "string", "integer", "long", "boolean", "enum", "structure", "list":
				name := shape.Name
				if optional {
					return "*" + name
				}
				return name
			}
		}
	}
	switch target {
	case "smithy.api#String", "smithy.api#Timestamp", "smithy.api#Blob":
		if optional {
			return "*string"
		}
		return "string"
	case "smithy.api#Integer", "smithy.api#Long":
		if optional {
			return "*int64"
		}
		return "int64"
	case "smithy.api#Boolean":
		if optional {
			return "*bool"
		}
		return "bool"
	default:
		name := exportedIdentifier(localName(target))
		if optional {
			return "*" + name
		}
		return name
	}
}

func (g generator) inputMember(op operationSpec, name string) memberSpec {
	input, ok := g.ir.Shapes[op.Input]
	if !ok {
		panic("missing input shape " + op.Input)
	}
	for _, member := range input.Members {
		if member.Name == name {
			return member
		}
	}
	panic("missing input member " + op.Input + "." + name)
}

func (g generator) successType(op operationSpec) string {
	output, ok := g.ir.Shapes[op.Output]
	if !ok {
		return "struct{}"
	}
	for _, member := range output.Members {
		if member.NestedProperties {
			return g.goType(member.Target, false)
		}
	}
	return output.Name + "Body"
}

func (g generator) outputFlattens(id string) bool {
	shape := g.ir.Shapes[id]
	if !shape.Output {
		return false
	}
	for _, member := range shape.Members {
		if member.NestedProperties {
			return true
		}
	}
	return false
}

func (g generator) serviceName() string {
	if strings.TrimSpace(g.ir.Service.Runtime.ServiceName) != "" {
		return g.ir.Service.Runtime.ServiceName
	}
	if strings.TrimSpace(g.ir.Service.Name) != "" {
		return g.ir.Service.Name
	}
	return g.ir.Projection
}

func isDocumentMember(member memberSpec) bool {
	return member.HTTPBinding == nil || member.HTTPBinding.Location == "" || member.HTTPBinding.Location == "document"
}

func sortedBindings(bindings []bindingSpec) []bindingSpec {
	out := append([]bindingSpec(nil), bindings...)
	sort.Slice(out, func(i, j int) bool {
		if out[i].Name == out[j].Name {
			return out[i].Member < out[j].Member
		}
		return out[i].Name < out[j].Name
	})
	return out
}

var wordBoundary = regexp.MustCompile(`[^A-Za-z0-9]+`)

func exportedIdentifier(name string) string {
	if name == "" {
		return "Value"
	}
	parts := wordBoundary.Split(name, -1)
	var out strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		runes := []rune(part)
		for i, r := range runes {
			if i == 0 {
				out.WriteRune(unicode.ToUpper(r))
			} else {
				out.WriteRune(r)
			}
		}
	}
	value := out.String()
	if value == "" {
		value = "Value"
	}
	if value == "Id" {
		return "ID"
	}
	value = strings.ReplaceAll(value, "OrgId", "OrgID")
	value = strings.ReplaceAll(value, "MemberId", "MemberID")
	value = strings.ReplaceAll(value, "RequestId", "RequestID")
	value = strings.ReplaceAll(value, "Acl", "ACL")
	value = strings.ReplaceAll(value, "Api", "API")
	value = strings.ReplaceAll(value, "Url", "URL")
	if first := []rune(value)[0]; unicode.IsDigit(first) {
		return "N" + value
	}
	return value
}

func localName(shapeID string) string {
	if idx := strings.LastIndex(shapeID, "#"); idx >= 0 {
		return shapeID[idx+1:]
	}
	return shapeID
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
