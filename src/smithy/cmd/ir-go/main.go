type contractIR = contract.IR
type shapeSpec = contract.Shape
type constraintsSpec = contract.Constraints
type memberSpec = contract.Member
type enumValueSpec = contract.EnumValue
type operationSpec = contract.Operation
type bindingSpec = contract.BoundMember
type payloadSpec = contract.PayloadBinding
type problemSpec = contract.Problem

func main() {
	var irPath string
	var mode string
	var packageName string
	var bindingName string
	var catalog string
	var outPath string
	var openAPIFormat string
	var serverURL string
	flag.StringVar(&irPath, "ir", "", "Verself contract IR JSON")
	flag.StringVar(&mode, "mode", "contract", "generation mode: contract, identity-catalog, catalog-json, proto, or openapi")
	flag.StringVar(&packageName, "package", "", "generated Go package name")
	flag.StringVar(&bindingName, "binding", "Public", "handler interface name prefix, for example Public or Internal")
	flag.StringVar(&catalog, "catalog", "", "catalog-json name: iam, audit, or observability")
	flag.StringVar(&outPath, "out", "", "output file")
	flag.StringVar(&openAPIFormat, "openapi-format", "3.1", "OpenAPI output format: 3.0 or 3.1")
	flag.StringVar(&serverURL, "server-url", "", "OpenAPI server URL")
	flag.Parse()

	if strings.TrimSpace(irPath) == "" || strings.TrimSpace(outPath) == "" {
		fail(errors.New("-ir and -out are required"))
	}
	ir, err := readIR(irPath)
	if err != nil {
		fail(err)
	}
	if len(ir.Operations) == 0 {
		fail(errors.New("IR has no operations"))
	}

	var data []byte
	formatGo := false
	switch mode {
	case "contract":
		if packageName == "" {
			packageName = "contractapi"
		}
		data, err = generateContract(ir, packageName, bindingName)
		formatGo = true
	case "identity-catalog":
		if packageName == "" {
			packageName = "identity"
		}
		data, err = generateIdentityCatalog(ir, packageName)
		formatGo = true
	case "catalog-json":
		data, err = generateCatalogJSON(ir, catalog)
	case "proto":
		data, err = generateProto(ir)
	case "openapi":
		data, err = generateOpenAPI(ir, openAPIFormat, serverURL)
	default:
		err = fmt.Errorf("unsupported mode %q", mode)
	}
	if err != nil {
		fail(err)
	}
	if formatGo {
		data, err = format.Source(data)
		if err != nil {
			_, _ = os.Stderr.Write(data)
			fail(fmt.Errorf("format generated Go: %w", err))
		}
	}
	if len(data) == 0 || data[len(data)-1] != '\n' {
		data = append(data, '\n')
	}
	if err := os.WriteFile(outPath, data, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

func readIR(path string) (*contractIR, error) {
	ir, err := contract.ReadFile(path)
	if err != nil {
		return nil, err
	}
	for id, shape := range ir.Shapes {
		shape.Name = localName(id)
		for i := range shape.Members {
			shape.Members[i].GoName = goName(shape.Members[i].Name)
			shape.Members[i].Type = goTypeForTarget(&ir, shape.Members[i].Target)
			if shape.Members[i].JSONName == "" {
				shape.Members[i].JSONName = shape.Members[i].Name
			}
		}
		ir.Shapes[id] = shape
	}
	for _, op := range ir.Operations {
		input := ir.Shapes[op.Input]
		input.Input = true
		ir.Shapes[op.Input] = input
		output := ir.Shapes[op.Output]
		output.Output = true
		ir.Shapes[op.Output] = output
	}
	sortOperations(ir.Operations)
	return &ir, nil
}

func generateContract(ir *contractIR, packageName string, bindingName string) ([]byte, error) {
	bindingName = goName(strings.TrimSpace(bindingName))
	if bindingName == "" {
		return nil, errors.New("contract binding name is required")
	}
	scalars, enums, structs, lists, maps := classifyShapes(ir)
	var b bytes.Buffer
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	fmt.Fprintf(&b, "import (\n")
	fmt.Fprintf(&b, "\t\"context\"\n")
	fmt.Fprintf(&b, ")\n\n")
	fmt.Fprintf(&b, "// Code generated by //src/smithy/cmd/ir-go from %s. DO NOT EDIT.\n\n", ir.Projection)
	writeRuntimeTypes(&b)
	writeScalars(&b, ir, scalars)
	writeEnums(&b, ir, enums)
	writeLists(&b, ir, lists)
	writeMaps(&b, ir, maps)
	writeStructs(&b, ir, structs)
	writeOutputBodies(&b, ir)
	writeDescriptors(&b, ir)
	writeHandlerTypes(&b, ir.Operations, bindingName)
	return b.Bytes(), nil
}

func generateIdentityCatalog(ir *contractIR, packageName string) ([]byte, error) {
	serviceName := strings.TrimSpace(ir.Service.Runtime.ServiceName)
	if serviceName == "" {
		return nil, errors.New("IR service runtime missing serviceName")
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	fmt.Fprintf(&b, "import runtimeiam \"github.com/verself/service-runtime/iam\"\n\n")
	fmt.Fprintf(&b, "// Code generated by //src/smithy/cmd/ir-go from %s. DO NOT EDIT.\n\n", ir.Projection)
	fmt.Fprintf(&b, "func smithyIAMServiceOperations() ServiceOperations {\n")
	fmt.Fprintf(&b, "\treturn ServiceOperations{Service: %q, Operations: []Operation{\n", serviceName)
	for _, op := range ir.Catalogs.IAM {
		fmt.Fprintf(&b, "\t\t{OperationID: %q, Permission: runtimeiam.Permission(%q), Resource: runtimeiam.ResourceKind(%q), Action: runtimeiam.Action(%q), OrgScope: runtimeiam.OrgScope(%q), MemberEligible: %t},\n",
			op.OperationID, op.Permission, op.Resource, op.Action, op.OrgScope, op.MemberEligible)
	}
	fmt.Fprintf(&b, "\t}}\n")
	fmt.Fprintf(&b, "}\n")
	return b.Bytes(), nil
}

func generateCatalogJSON(ir *contractIR, catalog string) ([]byte, error) {
	var value any
	switch strings.TrimSpace(catalog) {
	case "iam":
		value = ir.Catalogs.IAM
	case "audit":
		value = ir.Catalogs.Audit
	case "observability":
		value = ir.Catalogs.Observability
	default:
		return nil, fmt.Errorf("unsupported catalog %q", catalog)
	}
	return json.MarshalIndent(value, "", "  ")
}

func generateProto(ir *contractIR) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "syntax = \"proto3\";\n\n")
	fmt.Fprintf(&b, "package %s;\n\n", protoPackage(ir))
	if protoUsesStruct(ir) {
		fmt.Fprintf(&b, "import \"google/protobuf/struct.proto\";\n\n")
	}
	fmt.Fprintf(&b, "option go_package = %q;\n\n", protoGoPackage(ir))
	for _, id := range sortedShapeIDs(ir, "enum") {
		shape := ir.Shapes[id]
		fmt.Fprintf(&b, "enum %s {\n", goName(shape.Name))
		fmt.Fprintf(&b, "  %s_UNSPECIFIED = 0;\n", strings.ToUpper(lowerSnake(shape.Name)))
		for i, value := range shape.Enum {
			fmt.Fprintf(&b, "  %s_%s = %d;\n", strings.ToUpper(lowerSnake(shape.Name)), strings.ToUpper(lowerSnake(value.Name)), i+1)
		}
		fmt.Fprintf(&b, "}\n\n")
	}
	for _, id := range sortedShapeIDs(ir, "structure") {
		shape := ir.Shapes[id]
		if len(shape.Members) == 0 {
			continue
		}
		fmt.Fprintf(&b, "message %s {\n", goName(shape.Name))
		for _, member := range shape.Members {
			number := 0
			if member.ProtoField != nil {
				number = member.ProtoField.Number
			}
			if number == 0 {
				continue
			}
			fmt.Fprintf(&b, "  %s %s = %d;\n", protoType(ir, member.Target), lowerSnake(member.Name), number)
		}
		fmt.Fprintf(&b, "}\n\n")
	}
	fmt.Fprintf(&b, "service %s {\n", goName(ir.Service.Name))
	for _, op := range ir.Operations {
		fmt.Fprintf(&b, "  rpc %s(%s) returns (%s);\n", goName(op.Name), goName(localName(op.Input)), goName(localName(op.Output)))
	}
	fmt.Fprintf(&b, "}\n")
	return b.Bytes(), nil
}

func generateOpenAPI(ir *contractIR, format string, serverURL string) ([]byte, error) {
	version := "3.1.0"
	switch strings.TrimSpace(format) {
	case "", "3.1":
		version = "3.1.0"
	case "3.0":
		version = "3.0.3"
	case "3.2":
		version = "3.2.0"
	default:
		return nil, fmt.Errorf("unsupported OpenAPI format %q", format)
	}
	components := map[string]any{
		"schemas":         openAPISchemas(ir),
		"securitySchemes": openAPISecuritySchemes(ir),
	}
	doc := map[string]any{
		"openapi": version,
		"info": map[string]any{
			"title":   openAPITitle(ir),
			"version": ir.Service.Version,
		},
		"paths":      openAPIPaths(ir),
		"components": components,
	}
	if strings.TrimSpace(serverURL) != "" {
		doc["servers"] = []map[string]any{{"url": strings.TrimSpace(serverURL)}}
	}
	return json.MarshalIndent(doc, "", "  ")
}

func openAPITitle(ir *contractIR) string {
	service := strings.TrimSpace(ir.Service.Runtime.ServiceName)
	if service == "" {
		service = strings.TrimSpace(ir.Service.Name)
	}
	service = strings.TrimSuffix(service, "-service")
	service = strings.ReplaceAll(service, "-", " ")
	service = strings.ReplaceAll(service, "_", " ")
	parts := strings.Fields(service)
	for i, part := range parts {
		if strings.EqualFold(part, "iam") {
			parts[i] = "IAM"
			continue
		}
		parts[i] = strings.ToUpper(part[:1]) + part[1:]
	}
	if len(parts) == 0 {
		return "Verself API"
	}
	return strings.Join(parts, " ") + " Service"
}

func openAPISchemas(ir *contractIR) map[string]any {
	out := map[string]any{
		"ErrorModel": map[string]any{
			"type": "object",
			"properties": map[string]any{
				"type":        map[string]any{"type": "string"},
				"title":       map[string]any{"type": "string"},
				"status":      map[string]any{"type": "integer", "minimum": 100, "maximum": 599},
				"detail":      map[string]any{"type": "string"},
				"instance":    map[string]any{"type": "string"},
				"code":        map[string]any{"type": "string"},
				"requestId":   map[string]any{"type": "string"},
				"traceparent": map[string]any{"type": "string"},
				"errors":      map[string]any{"type": "array", "items": map[string]any{"type": "object"}},
			},
		},
	}
	ids := make([]string, 0, len(ir.Shapes))
	for id := range ir.Shapes {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		shape := ir.Shapes[id]
		name := goName(shape.Name)
		if name == "" {
			continue
		}
		out[name] = openAPISchemaForShape(ir, shape)
	}
	return out
}

func openAPISchemaForShape(ir *contractIR, shape shapeSpec) map[string]any {
	switch shape.Kind {
	case "string":
		schema := map[string]any{"type": "string"}
		addOpenAPIConstraints(schema, shape.Constraints)
		return schema
	case "integer":
		schema := map[string]any{"type": "integer", "format": "int32"}
		addOpenAPIConstraints(schema, shape.Constraints)
		return schema
	case "long":
		schema := map[string]any{"type": "integer", "format": "int64"}
		addOpenAPIConstraints(schema, shape.Constraints)
		return schema
	case "float", "double":
		schema := map[string]any{"type": "number", "format": shape.Kind}
		addOpenAPIConstraints(schema, shape.Constraints)
		return schema
	case "boolean":
		return map[string]any{"type": "boolean"}
	case "blob":
		schema := map[string]any{"type": "string", "format": "byte"}
		addOpenAPIConstraints(schema, shape.Constraints)
		return schema
	case "enum":
		values := make([]string, 0, len(shape.Enum))
		for _, value := range shape.Enum {
			values = append(values, value.Value)
		}
		sort.Strings(values)
		return map[string]any{"type": "string", "enum": values}
	case "list":
		items := map[string]any{}
		if shape.Member != nil {
			items = openAPISchemaForTarget(ir, shape.Member.Target)
		}
		return map[string]any{"type": "array", "items": items}
	case "map":
		additionalProperties := any(true)
		if shape.Value != nil {
			additionalProperties = openAPISchemaForTarget(ir, shape.Value.Target)
		}
		return map[string]any{"type": "object", "additionalProperties": additionalProperties}
	case "structure":
		return openAPIObjectSchemaForMembers(ir, shape.Members)
	default:
		return map[string]any{}
	}
}

func openAPIObjectSchemaForMembers(ir *contractIR, members []memberSpec) map[string]any {
	properties := map[string]any{}
	required := make([]string, 0)
	for _, member := range members {
		jsonName := member.JSONName
		if jsonName == "" {
			jsonName = member.Name
		}
		properties[jsonName] = openAPISchemaForTarget(ir, member.Target)
		if member.Required {
			required = append(required, jsonName)
		}
	}
	sort.Strings(required)
	schema := map[string]any{
		"type":       "object",
		"properties": properties,
	}
	if len(required) > 0 {
		schema["required"] = required
	}
	return schema
}

func openAPISchemaForTarget(ir *contractIR, target string) map[string]any {
	if strings.HasPrefix(target, "smithy.api#") {
		switch localName(target) {
		case "String":
			return map[string]any{"type": "string"}
		case "Blob":
			return map[string]any{"type": "string", "format": "byte"}
		case "Timestamp":
			return map[string]any{"type": "string", "format": "date-time"}
		case "Integer":
			return map[string]any{"type": "integer", "format": "int32"}
		case "Long":
			return map[string]any{"type": "integer", "format": "int64"}
		case "Float":
			return map[string]any{"type": "number", "format": "float"}
		case "Double":
			return map[string]any{"type": "number", "format": "double"}
		case "Boolean":
			return map[string]any{"type": "boolean"}
		case "Document":
			return map[string]any{"type": "object", "additionalProperties": true}
		default:
			return map[string]any{"type": "string"}
		}
	}
	return map[string]any{"$ref": "#/components/schemas/" + goName(localName(target))}
}

func openAPIPayloadSchema(ir *contractIR, payload *payloadSpec) map[string]any {
	if payload == nil {
		return map[string]any{}
	}
	switch payload.Kind {
	case "blob":
		return map[string]any{"type": "string", "format": "binary"}
	case "string":
		return map[string]any{"type": "string"}
	default:
		return openAPISchemaForTarget(ir, payload.Target)
	}
}

func payloadMediaType(payload *payloadSpec) string {
	if payload == nil {
		return "application/octet-stream"
	}
	if strings.TrimSpace(payload.MediaType) != "" {
		return strings.TrimSpace(payload.MediaType)
	}
	switch payload.Kind {
	case "blob":
		return "application/octet-stream"
	case "string":
		return "text/plain"
	default:
		return "application/json"
	}
}

func membersByName(shape shapeSpec, names []string) []memberSpec {
	allowed := map[string]bool{}
	for _, name := range names {
		allowed[name] = true
	}
	members := make([]memberSpec, 0, len(names))
	for _, member := range shape.Members {
		if allowed[member.Name] {
			members = append(members, member)
		}
	}
	return members
}

func addOpenAPIConstraints(schema map[string]any, constraints constraintsSpec) {
	if constraints.Pattern != "" {
		schema["pattern"] = constraints.Pattern
	}
	if constraints.Length.Min != nil {
		schema["minLength"] = *constraints.Length.Min
	}
	if constraints.Length.Max != nil {
		schema["maxLength"] = *constraints.Length.Max
	}
	if constraints.Range.Min != nil {
		schema["minimum"] = *constraints.Range.Min
	}
	if constraints.Range.Max != nil {
		schema["maximum"] = *constraints.Range.Max
	}
}

func openAPIPaths(ir *contractIR) map[string]any {
	paths := map[string]any{}
	for _, op := range ir.Operations {
		pathItem, _ := paths[op.HTTP.Path].(map[string]any)
		if pathItem == nil {
			pathItem = map[string]any{}
			paths[op.HTTP.Path] = pathItem
		}
		method := strings.ToLower(op.HTTP.Method)
		pathItem[method] = openAPIOperation(ir, op)
	}
	return paths
}

func openAPIOperation(ir *contractIR, op operationSpec) map[string]any {
	operation := map[string]any{
		"operationId": op.OperationID,
		"summary":     sentence(op.Name),
		"responses":   openAPIResponses(ir, op),
		"x-verself-contract": map[string]any{
			"shape_id":               op.ShapeID,
			"operation_id":           op.OperationID,
			"identity":               op.Verself.Identity.Mode,
			"audience":               op.Verself.Identity.Audience,
			"permission":             op.Verself.Authz.Permission,
			"organization_source":    op.Verself.Authz.Organization.Source,
			"organization_member":    op.Verself.Authz.Organization.Member,
			"audit_event":            op.Verself.Audit.Event,
			"resource":               op.Verself.Audit.Resource,
			"action":                 op.Verself.Audit.Action,
			"rate_limit_bucket":      op.Verself.RateLimit.Bucket,
			"request_body_max_bytes": op.Verself.RequestBudget.MaxBytes,
			"idempotency":            op.Verself.Idempotency.Policy,
		},
	}
	parameters := openAPIParameters(ir, op)
	if len(parameters) > 0 {
		operation["parameters"] = parameters
	}
	if requestBody := openAPIRequestBody(ir, op); requestBody != nil {
		operation["requestBody"] = requestBody
	}
	if security := openAPIOperationSecurity(op); len(security) > 0 {
		operation["security"] = security
	}
	return operation
}

func openAPIParameters(ir *contractIR, op operationSpec) []map[string]any {
	input := ir.Shapes[op.Input]
	out := make([]map[string]any, 0)
	for _, binding := range sortedBindings(op.Bindings.Labels) {
		if member, ok := inputMemberByName(input, binding.Member); ok {
			out = append(out, openAPIParameter(ir, binding.Name, "path", true, member))
		}
	}
	for _, binding := range sortedBindings(op.Bindings.Queries) {
		if member, ok := inputMemberByName(input, binding.Member); ok {
			out = append(out, openAPIParameter(ir, binding.Name, "query", member.Required, member))
		}
	}
	for _, binding := range sortedBindings(op.Bindings.Headers) {
		if member, ok := inputMemberByName(input, binding.Member); ok {
			out = append(out, openAPIParameter(ir, binding.Name, "header", member.Required, member))
		}
	}
	return out
}

func openAPIParameter(ir *contractIR, name string, in string, required bool, member memberSpec) map[string]any {
	return map[string]any{
		"name":     name,
		"in":       in,
		"required": required,
		"schema":   openAPISchemaForTarget(ir, member.Target),
	}
}

func openAPIRequestBody(ir *contractIR, op operationSpec) map[string]any {
	if op.Bindings.Payload != nil {
		return map[string]any{
			"required": op.Bindings.Payload.Required,
			"content": map[string]any{
				payloadMediaType(op.Bindings.Payload): map[string]any{
					"schema": openAPIPayloadSchema(ir, op.Bindings.Payload),
				},
			},
		}
	}
	if len(op.Bindings.DocumentMembers) == 0 {
		return nil
	}
	input := ir.Shapes[op.Input]
	documentMembers := map[string]bool{}
	for _, member := range op.Bindings.DocumentMembers {
		documentMembers[member] = true
	}
	members := make([]memberSpec, 0, len(op.Bindings.DocumentMembers))
	required := false
	for _, member := range input.Members {
		if documentMembers[member.Name] {
			members = append(members, member)
			required = required || member.Required
		}
	}
	return map[string]any{
		"required": required,
		"content": map[string]any{
			"application/json": map[string]any{
				"schema": openAPIObjectSchemaForMembers(ir, members),
			},
		},
	}
}

func openAPIResponses(ir *contractIR, op operationSpec) map[string]any {
	success := map[string]any{"description": "Success"}
	headers := openAPIResponseHeaders(ir, op)
	if len(headers) > 0 {
		success["headers"] = headers
	}
	if op.Bindings.ResponsePayload != nil {
		success["content"] = map[string]any{
			payloadMediaType(op.Bindings.ResponsePayload): map[string]any{
				"schema": openAPIPayloadSchema(ir, op.Bindings.ResponsePayload),
			},
		}
	} else {
		success["content"] = map[string]any{
			"application/json": map[string]any{
				"schema": openAPIOutputSchema(ir, op),
			},
		}
	}
	out := map[string]any{strconv.Itoa(op.HTTP.SuccessStatus): success}
	for _, problem := range op.Problems {
		status := strconv.Itoa(problem.Status)
		if _, ok := out[status]; ok {
			continue
		}
		schema := map[string]any{"$ref": "#/components/schemas/ErrorModel"}
		if problem.Name != "" {
			schema = map[string]any{"$ref": "#/components/schemas/" + goName(problem.Name)}
		}
		out[status] = map[string]any{
			"description": problem.Code,
			"content": map[string]any{
				"application/problem+json": map[string]any{
					"schema": schema,
				},
			},
		}
	}
	return out
}

func openAPIOutputSchema(ir *contractIR, op operationSpec) map[string]any {
	output := ir.Shapes[op.Output]
	if nested := nestedOutputMember(output); nested != nil {
		return openAPISchemaForTarget(ir, nested.Target)
	}
	if len(op.Bindings.ResponseDocumentMembers) > 0 {
		return openAPIObjectSchemaForMembers(ir, membersByName(output, op.Bindings.ResponseDocumentMembers))
	}
	return openAPIObjectSchemaForMembers(ir, output.Members)
}

func openAPIResponseHeaders(ir *contractIR, op operationSpec) map[string]any {
	if len(op.Bindings.ResponseHeaders) == 0 {
		return nil
	}
	output := ir.Shapes[op.Output]
	headers := map[string]any{}
	for _, binding := range sortedBindings(op.Bindings.ResponseHeaders) {
		if member, ok := inputMemberByName(output, binding.Member); ok {
			headers[binding.Name] = map[string]any{
				"schema": openAPISchemaForTarget(ir, member.Target),
			}
		}
	}
	return headers
}

func openAPIOperationSecurity(op operationSpec) []map[string][]string {
	switch op.Verself.Identity.Mode {
	case "bearer":
		return []map[string][]string{{"bearerAuth": {}}}
	case "spiffe_mtls":
		return []map[string][]string{{"mutualTLS": {}}}
	case "spiffe_mtls_bearer":
		return []map[string][]string{{"mutualTLS": {}, "bearerAuth": {}}}
	case "public":
		return nil
	default:
		return nil
	}
}

