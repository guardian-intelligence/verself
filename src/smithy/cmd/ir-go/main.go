func writeStructs(b *bytes.Buffer, ir *contractIR, ids []string) {
	for _, id := range ids {
		shape := ir.Shapes[id]
		if shape.Output {
			continue
		}
		if shape.Input {
			op := operationForInput(ir, id)
			transportMembers, bodyMembers := inputMemberSpecs(ir, shape)
			if len(bodyMembers) > 0 {
				fmt.Fprintf(b, "type %sBody struct {\n", goName(shape.Name))
				for _, member := range bodyMembers {
					fmt.Fprintf(b, "\t%s %s `%s`\n", member.GoName, member.Type, strings.Join(member.Tags, " "))
				}
				fmt.Fprintln(b, "}\n")
			}
			if op != nil && op.Bindings.Payload != nil {
				fmt.Fprintf(b, "type %s struct {\n", goName(shape.Name))
				for _, member := range transportMembers {
					writeGoMember(b, member)
				}
				fmt.Fprintf(b, "\tBody %s\n", payloadGoType(ir, op.Bindings.Payload))
				fmt.Fprintln(b, "}\n")
			} else if len(bodyMembers) > 0 {
				fmt.Fprintf(b, "type %s struct {\n", goName(shape.Name))
				for _, member := range transportMembers {
					writeGoMember(b, member)
				}
				fmt.Fprintf(b, "\tBody %sBody\n", goName(shape.Name))
				fmt.Fprintln(b, "}\n")
			} else if len(transportMembers) > 0 {
				fmt.Fprintf(b, "type %s struct {\n", goName(shape.Name))
				for _, member := range transportMembers {
					writeGoMember(b, member)
				}
				fmt.Fprintln(b, "}\n")
			} else {
				fmt.Fprintf(b, "type %s struct{}\n", goName(shape.Name))
			}
			fmt.Fprintln(b)
			continue
		}
		members := jsonMemberSpecsForStructure(ir, shape)
		if len(members) == 0 {
			fmt.Fprintf(b, "type %s struct{}\n\n", goName(shape.Name))
			continue
		}
		fmt.Fprintf(b, "type %s struct {\n", goName(shape.Name))
		for _, member := range members {
			fmt.Fprintf(b, "\t%s %s `%s`\n", member.GoName, member.Type, strings.Join(member.Tags, " "))
		}
		fmt.Fprintln(b, "}\n")
	}
}

func writeGoMember(b *bytes.Buffer, member memberSpec) {
	if len(member.Tags) == 0 {
		fmt.Fprintf(b, "\t%s %s\n", member.GoName, member.Type)
		return
	}
	fmt.Fprintf(b, "\t%s %s `%s`\n", member.GoName, member.Type, strings.Join(member.Tags, " "))
}

func writeOutputBodies(b *bytes.Buffer, ir *contractIR) {
	written := map[string]bool{}
	writtenOutputs := map[string]bool{}
	for _, op := range ir.Operations {
		output := ir.Shapes[op.Output]
		outputName := goName(output.Name)
		if writtenOutputs[outputName] {
			continue
		}
		writtenOutputs[outputName] = true
		if op.Bindings.ResponsePayload != nil {
			fmt.Fprintf(b, "type %s struct {\n", outputName)
			for _, member := range headerMemberSpecs(ir, output, op.Bindings.ResponseHeaders) {
				fmt.Fprintf(b, "\t%s %s `%s`\n", member.GoName, member.Type, strings.Join(member.Tags, " "))
			}
			fmt.Fprintf(b, "\tBody %s\n", payloadGoType(ir, op.Bindings.ResponsePayload))
			fmt.Fprintln(b, "}\n")
			continue
		}
		if nested := nestedOutputMember(output); nested != nil {
			fmt.Fprintf(b, "type %s struct {\n\tBody %s\n}\n\n", outputName, goTypeForTarget(ir, nested.Target))
			continue
		}
		bodyName := outputName + "Body"
		if !written[bodyName] {
			written[bodyName] = true
			fmt.Fprintf(b, "type %s struct {\n", bodyName)
			for _, member := range jsonMemberSpecsForMembers(ir, output, op.Bindings.ResponseDocumentMembers) {
				fmt.Fprintf(b, "\t%s %s `%s`\n", member.GoName, member.Type, strings.Join(member.Tags, " "))
			}
			fmt.Fprintln(b, "}\n")
		}
		fmt.Fprintf(b, "type %s struct {\n\tBody %s\n}\n\n", outputName, bodyName)
	}
}

