package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
	"unicode"

	"github.com/verself/verself/src/smithy/internal/contract"
)

type contractIR = contract.IR
type bindingSpec = contract.BoundMember
type shapeSpec = contract.Shape
type memberSpec = contract.Member
type operationSpec = contract.Operation

type generator struct {
	ir contractIR
}

func main() {
	var irPath string
	var outPath string
	flag.StringVar(&irPath, "ir", "", "Verself contract IR JSON")
	flag.StringVar(&outPath, "out", "", "generated TypeScript file")
	flag.Parse()

	if strings.TrimSpace(irPath) == "" || strings.TrimSpace(outPath) == "" {
		fail(errors.New("-ir and -out are required"))
	}
	ir, err := readIR(irPath)
	if err != nil {
		fail(err)
	}
	if len(ir.Operations) == 0 {
		fail(errors.New("IR has no operations"))
	}
	data, err := generator{ir: ir}.generate()
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(outPath, data, 0o644); err != nil {
		fail(err)
	}
}

func readIR(path string) (contractIR, error) {
	ir, err := contract.ReadFile(path)
	if err != nil {
		return contractIR{}, err
	}
	for id, shape := range ir.Shapes {
		if strings.TrimSpace(shape.Name) == "" {
			return contractIR{}, fmt.Errorf("shape %s has no name", id)
		}
		ir.Shapes[id] = shape
	}
	return ir, nil
}

func (g generator) generate() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by //src/smithy/cmd/ir-sdk-ts. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "export const serviceName = %q;\n\n", g.serviceName())
	g.writeScalarAliases(&b)
	g.writeEnums(&b)
	g.writeLists(&b)
	g.writeStructures(&b)
	g.writeOperationTypes(&b)
	g.writeTransportTypes(&b)
	g.writeTransport(&b)
	g.writeHelpers(&b)
	return b.Bytes(), nil
}

func (g generator) writeScalarAliases(out *bytes.Buffer) {
	for _, id := range g.sortedShapeIDs() {
		shape := g.ir.Shapes[id]
		switch shape.Kind {
		case "string":
			fmt.Fprintf(out, "export type %s = string;\n\n", shape.Name)
		case "integer", "long":
			fmt.Fprintf(out, "export type %s = number;\n\n", shape.Name)
		case "boolean":
			fmt.Fprintf(out, "export type %s = boolean;\n\n", shape.Name)
		}
	}
}

func (g generator) writeEnums(out *bytes.Buffer) {
	for _, id := range g.sortedShapeIDs() {
		shape := g.ir.Shapes[id]
		if shape.Kind != "enum" {
			continue
		}
		values := make([]string, 0, len(shape.Enum))
		for _, value := range shape.Enum {
			values = append(values, fmt.Sprintf("%q", value.Value))
		}
		sort.Strings(values)
		fmt.Fprintf(out, "export type %s = %s;\n\n", shape.Name, strings.Join(values, " | "))
	}
}

func (g generator) writeLists(out *bytes.Buffer) {
	for _, id := range g.sortedShapeIDs() {
		shape := g.ir.Shapes[id]
		if shape.Kind != "list" || shape.Member == nil {
			continue
		}
		fmt.Fprintf(out, "export type %s = ReadonlyArray<%s>;\n\n", shape.Name, g.tsType(shape.Member.Target, false))
	}
}

func (g generator) writeStructures(out *bytes.Buffer) {
	for _, id := range g.sortedShapeIDs() {
		shape := g.ir.Shapes[id]
		if shape.Kind != "structure" || shape.Input {
			continue
		}
		if shape.Output && g.outputFlattens(id) {
			continue
		}
		typeName := shape.Name
		if shape.Output {
			typeName = shape.Name + "Body"
		}
		g.writeInterface(out, typeName, shape.Members, nil)
	}
}

func (g generator) writeOperationTypes(out *bytes.Buffer) {
	for _, op := range g.sortedOperations() {
		input, ok := g.ir.Shapes[op.Input]
		if !ok {
			continue
		}
		requestFields := make([]memberSpec, 0, len(input.Members)+1)
		bodyFields := make([]memberSpec, 0, len(input.Members))
		for _, member := range input.Members {
			if isDocumentMember(member) {
				bodyFields = append(bodyFields, member)
			} else {
				requestFields = append(requestFields, member)
			}
		}
		if len(bodyFields) > 0 {
			g.writeInterface(out, input.Name+"Body", bodyFields, nil)
			requestFields = append(requestFields, memberSpec{Name: "body", JSONName: "body", Target: input.Name + "Body", Required: true})
		}
		g.writeInterface(out, op.Name+"Request", requestFields, map[string]string{"body": input.Name + "Body"})
	}
}

func (g generator) writeTransportTypes(out *bytes.Buffer) {
	out.WriteString("export interface ErrorModel {\n")
	out.WriteString("  readonly $schema?: string;\n")
	out.WriteString("  readonly type?: string;\n")
	out.WriteString("  readonly title?: string;\n")
	out.WriteString("  readonly status?: number;\n")
	out.WriteString("  readonly detail?: string;\n")
	out.WriteString("  readonly instance?: string;\n")
	out.WriteString("  readonly code?: string;\n")
	out.WriteString("  readonly requestId?: string;\n")
	out.WriteString("  readonly traceparent?: string;\n")
	out.WriteString("  readonly errors?: ReadonlyArray<Record<string, unknown>>;\n")
	out.WriteString("}\n\n")
	out.WriteString("export interface TransportResult<T> {\n")
	out.WriteString("  readonly response: Response;\n")
	out.WriteString("  readonly bodyText: string;\n")
	out.WriteString("  readonly data?: T;\n")
	out.WriteString("  readonly error?: ErrorModel;\n")
	out.WriteString("}\n\n")
	out.WriteString("export interface IAMTransportOptions {\n")
	out.WriteString("  readonly baseUrl: string;\n")
	out.WriteString("  readonly headers?: HeadersInit;\n")
	out.WriteString("  readonly fetch?: typeof fetch;\n")
	out.WriteString("}\n\n")
	out.WriteString("export interface IAMTransport {\n")
	for _, op := range g.sortedOperations() {
		method := lowerCamel(op.Name)
		requestType := op.Name + "Request"
		success := g.successType(op)
		if g.requestHasRequiredFields(op) {
			fmt.Fprintf(out, "  %s(input: %s): Promise<TransportResult<%s>>;\n", method, requestType, success)
		} else {
			fmt.Fprintf(out, "  %s(input?: %s): Promise<TransportResult<%s>>;\n", method, requestType, success)
		}
	}
	out.WriteString("}\n\n")
}

func (g generator) writeTransport(out *bytes.Buffer) {
	out.WriteString("export function createIAMTransport(options: IAMTransportOptions): IAMTransport {\n")
	out.WriteString("  const baseUrl = normalizeBaseUrl(options.baseUrl);\n")
	out.WriteString("  const fetchFn = options.fetch ?? globalThis.fetch?.bind(globalThis);\n")
	out.WriteString("  if (fetchFn === undefined) {\n")
	out.WriteString("    throw new Error(`${serviceName} transport requires a fetch implementation`);\n")
	out.WriteString("  }\n")
	out.WriteString("  const baseHeaders = new Headers(options.headers);\n\n")
	out.WriteString("  async function send<T>(spec: RequestSpec): Promise<TransportResult<T>> {\n")
	out.WriteString("    const url = new URL(spec.path, baseUrl);\n")
	out.WriteString("    for (const [name, value] of Object.entries(spec.query ?? {})) {\n")
	out.WriteString("      if (value !== undefined) url.searchParams.set(name, String(value));\n")
	out.WriteString("    }\n")
	out.WriteString("    const headers = new Headers(baseHeaders);\n")
	out.WriteString("    if (!headers.has(\"Accept\")) headers.set(\"Accept\", \"application/json\");\n")
	out.WriteString("    let body: BodyInit | undefined;\n")
	out.WriteString("    if (spec.body !== undefined) {\n")
	out.WriteString("      if (!headers.has(\"Content-Type\")) headers.set(\"Content-Type\", \"application/json\");\n")
	out.WriteString("      body = JSON.stringify(removeUndefined(spec.body));\n")
	out.WriteString("    }\n")
	out.WriteString("    for (const [name, value] of Object.entries(spec.headers ?? {})) {\n")
	out.WriteString("      if (value !== undefined) headers.set(name, String(value));\n")
	out.WriteString("    }\n")
	out.WriteString("    const init: RequestInit = { headers, method: spec.method };\n")
	out.WriteString("    if (body !== undefined) init.body = body;\n")
	out.WriteString("    const response = await fetchFn(url, init);\n")
	out.WriteString("    const bodyText = await response.text();\n")
	out.WriteString("    const payload = parseJSON(bodyText);\n")
	out.WriteString("    if (response.status === spec.successStatus) {\n")
	out.WriteString("      return { response, bodyText, data: payload as T };\n")
	out.WriteString("    }\n")
	out.WriteString("    if (payload === undefined) return { response, bodyText };\n")
	out.WriteString("    return { response, bodyText, error: payload as ErrorModel };\n")
	out.WriteString("  }\n\n")
	out.WriteString("  return {\n")
	for _, op := range g.sortedOperations() {
		g.writeOperationMethod(out, op)
	}
	out.WriteString("  };\n")
	out.WriteString("}\n\n")
}

func (g generator) writeOperationMethod(out *bytes.Buffer, op operationSpec) {
	method := lowerCamel(op.Name)
	requestType := op.Name + "Request"
	defaultInput := ""
	if !g.requestHasRequiredFields(op) {
		defaultInput = " = {}"
	}
	fmt.Fprintf(out, "    %s(input: %s%s) {\n", method, requestType, defaultInput)
	fmt.Fprintf(out, "      return send<%s>({\n", g.successType(op))
	fmt.Fprintf(out, "        method: %q,\n", op.HTTP.Method)
	fmt.Fprintf(out, "        path: %s,\n", g.pathExpression(op))
	fmt.Fprintf(out, "        successStatus: %d,\n", op.HTTP.SuccessStatus)
	if len(op.Bindings.Queries) > 0 {
		out.WriteString("        query: {\n")
		for _, binding := range sortedBindings(op.Bindings.Queries) {
			member := g.inputMember(op, binding.Member)
			fmt.Fprintf(out, "          %q: input.%s,\n", binding.Name, member.Name)
		}
		out.WriteString("        },\n")
	}
	if len(op.Bindings.Headers) > 0 {
		out.WriteString("        headers: {\n")
		for _, binding := range sortedBindings(op.Bindings.Headers) {
			member := g.inputMember(op, binding.Member)
			fmt.Fprintf(out, "          %q: input.%s,\n", binding.Name, member.Name)
		}
		out.WriteString("        },\n")
	}
	if len(op.Bindings.DocumentMembers) > 0 {
		out.WriteString("        body: input.body,\n")
	}
	out.WriteString("      });\n")
	out.WriteString("    },\n")
}

func (g generator) writeHelpers(out *bytes.Buffer) {
	out.WriteString("interface RequestSpec {\n")
	out.WriteString("  readonly method: string;\n")
	out.WriteString("  readonly path: string;\n")
	out.WriteString("  readonly successStatus: number;\n")
	out.WriteString("  readonly query?: Record<string, string | number | boolean | undefined>;\n")
	out.WriteString("  readonly headers?: Record<string, string | number | boolean | undefined>;\n")
	out.WriteString("  readonly body?: unknown;\n")
	out.WriteString("}\n\n")
	out.WriteString("function normalizeBaseUrl(baseUrl: string): string {\n")
	out.WriteString("  const trimmed = baseUrl.trim();\n")
	out.WriteString("  if (trimmed === \"\") throw new Error(`${serviceName} transport baseUrl is required`);\n")
	out.WriteString("  return trimmed.endsWith(\"/\") ? trimmed : `${trimmed}/`;\n")
	out.WriteString("}\n\n")
	out.WriteString("function parseJSON(bodyText: string): unknown {\n")
	out.WriteString("  if (bodyText.trim() === \"\") return undefined;\n")
	out.WriteString("  return JSON.parse(bodyText);\n")
	out.WriteString("}\n\n")
	out.WriteString("function removeUndefined(input: unknown): unknown {\n")
	out.WriteString("  if (Array.isArray(input)) return input.map(removeUndefined);\n")
	out.WriteString("  if (input !== null && typeof input === \"object\") {\n")
	out.WriteString("    return Object.fromEntries(\n")
	out.WriteString("      Object.entries(input).filter(([, value]) => value !== undefined).map(([key, value]) => [key, removeUndefined(value)]),\n")
	out.WriteString("    );\n")
	out.WriteString("  }\n")
	out.WriteString("  return input;\n")
	out.WriteString("}\n")
}

func (g generator) writeInterface(out *bytes.Buffer, name string, members []memberSpec, overrideTypes map[string]string) {
	fmt.Fprintf(out, "export interface %s {\n", name)
	for _, member := range members {
		fieldName := member.JSONName
		if fieldName == "" {
			fieldName = member.Name
		}
		fieldType, ok := overrideTypes[member.Name]
		if !ok {
			fieldType = g.tsType(member.Target, !member.Required)
		}
		optional := ""
		if !member.Required {
			optional = "?"
		}
		fmt.Fprintf(out, "  readonly %s%s: %s;\n", fieldName, optional, fieldType)
	}
	out.WriteString("}\n\n")
}

func (g generator) sortedShapeIDs() []string {
	ids := make([]string, 0, len(g.ir.Shapes))
	for id := range g.ir.Shapes {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool {
		left := g.ir.Shapes[ids[i]].Name
		right := g.ir.Shapes[ids[j]].Name
		if left == right {
			return ids[i] < ids[j]
		}
		return left < right
	})
	return ids
}

func (g generator) sortedOperations() []operationSpec {
	ops := append([]operationSpec(nil), g.ir.Operations...)
	sort.Slice(ops, func(i, j int) bool { return ops[i].Name < ops[j].Name })
	return ops
}

func (g generator) tsType(target string, optional bool) string {
	base := "unknown"
	if shape, ok := g.ir.Shapes[target]; ok {
		switch shape.Kind {
		case "string":
			base = shape.Name
		case "integer", "long":
			base = shape.Name
		case "boolean":
			base = shape.Name
		case "enum", "structure", "list":
			base = shape.Name
		}
	} else {
		switch target {
		case "smithy.api#String", "smithy.api#Timestamp", "smithy.api#Blob":
			base = "string"
		case "smithy.api#Integer", "smithy.api#Long":
			base = "number"
		case "smithy.api#Boolean":
			base = "boolean"
		default:
			base = exportedIdentifier(localName(target))
		}
	}
	if optional {
		return base
	}
	return base
}

func (g generator) inputMember(op operationSpec, name string) memberSpec {
	input := g.ir.Shapes[op.Input]
	for _, member := range input.Members {
		if member.Name == name {
			return member
		}
	}
	panic("missing input member " + op.Input + "." + name)
}

func (g generator) successType(op operationSpec) string {
	output, ok := g.ir.Shapes[op.Output]
	if !ok {
		return "undefined"
	}
	for _, member := range output.Members {
		if member.NestedProperties {
			return g.tsType(member.Target, false)
		}
	}
	return output.Name + "Body"
}

func (g generator) outputFlattens(id string) bool {
	shape := g.ir.Shapes[id]
	if !shape.Output {
		return false
	}
	for _, member := range shape.Members {
		if member.NestedProperties {
			return true
		}
	}
	return false
}

func (g generator) requestHasRequiredFields(op operationSpec) bool {
	input := g.ir.Shapes[op.Input]
	for _, member := range input.Members {
		if member.Required {
			return true
		}
	}
	return false
}

func (g generator) pathExpression(op operationSpec) string {
	path := op.HTTP.Path
	if len(op.Bindings.Labels) == 0 {
		return fmt.Sprintf("%q", path)
	}
	for _, binding := range sortedBindings(op.Bindings.Labels) {
		member := g.inputMember(op, binding.Member)
		replacement := fmt.Sprintf("${encodeURIComponent(String(input.%s))}", member.Name)
		path = strings.ReplaceAll(path, "{"+binding.Name+"}", replacement)
	}
	return "`" + path + "`"
}

func (g generator) serviceName() string {
	if strings.TrimSpace(g.ir.Service.Runtime.ServiceName) != "" {
		return g.ir.Service.Runtime.ServiceName
	}
	if strings.TrimSpace(g.ir.Service.Name) != "" {
		return g.ir.Service.Name
	}
	return g.ir.Projection
}

func isDocumentMember(member memberSpec) bool {
	return member.HTTPBinding == nil || member.HTTPBinding.Location == "" || member.HTTPBinding.Location == "document"
}

func sortedBindings(bindings []bindingSpec) []bindingSpec {
	out := append([]bindingSpec(nil), bindings...)
	sort.Slice(out, func(i, j int) bool {
		if out[i].Name == out[j].Name {
			return out[i].Member < out[j].Member
		}
		return out[i].Name < out[j].Name
	})
	return out
}

func lowerCamel(name string) string {
	exported := exportedIdentifier(name)
	runes := []rune(exported)
	if len(runes) == 0 {
		return "value"
	}
	runes[0] = unicode.ToLower(runes[0])
	return string(runes)
}

var wordBoundary = regexp.MustCompile(`[^A-Za-z0-9]+`)

func exportedIdentifier(name string) string {
	if name == "" {
		return "Value"
	}
	parts := wordBoundary.Split(name, -1)
	var out strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		runes := []rune(part)
		for i, r := range runes {
			if i == 0 {
				out.WriteRune(unicode.ToUpper(r))
			} else {
				out.WriteRune(r)
			}
		}
	}
	value := out.String()
	if value == "" {
		value = "Value"
	}
	return value
}

func localName(shapeID string) string {
	if idx := strings.LastIndex(shapeID, "#"); idx >= 0 {
		return shapeID[idx+1:]
	}
	return shapeID
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
