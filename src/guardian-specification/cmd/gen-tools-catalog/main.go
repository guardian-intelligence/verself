// Command gen-tools-catalog renders the Guardian tool catalog CUE document from
// the Bazel-owned pin graph. It is the single generator behind
// .config/guardian/tools.cue: the catalog can never drift from the materialized
// tool root because both read the same Starlark catalog (//src/guardian-specification/tools:catalog.bzl),
// projected here through a JSON intermediate.
//
// Input  (-in):  JSON object {"<name>": {"<os/arch>": "<executable>"}}
// Output (-out): CUE document the guardian resolver loads.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"sort"
)

func main() {
	in := flag.String("in", "", "path to the JSON catalog projection")
	out := flag.String("out", "", "path to write the generated CUE catalog")
	flag.Parse()

	if *in == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "gen-tools-catalog: -in and -out are required")
		os.Exit(2)
	}

	raw, err := os.ReadFile(*in)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-tools-catalog: read %s: %v\n", *in, err)
		os.Exit(1)
	}

	var catalog map[string]map[string]string
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&catalog); err != nil {
		fmt.Fprintf(os.Stderr, "gen-tools-catalog: decode %s: %v\n", *in, err)
		os.Exit(1)
	}

	doc, err := render(catalog)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gen-tools-catalog: %v\n", err)
		os.Exit(1)
	}

	if err := os.WriteFile(*out, doc, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "gen-tools-catalog: write %s: %v\n", *out, err)
		os.Exit(1)
	}
}

const header = `// Guardian tool catalog. GENERATED by
// //src/guardian-specification/cmd/gen-tools-catalog from the Bazel pin graph
// (//src/guardian-specification/tools:catalog.bzl). Do not edit by hand; run
// ` + "`" + `bazel run //src/guardian-specification/tools:write_tools_catalog` + "`" + `.
//
// Each entry names the executable ` + "`" + `guardian run <tool>` + "`" + ` resolves from the tool
// root (<root>/<name>/bin/<executable>): the golden image closure at
// $GUARDIAN_TOOLS_ROOT, or the Bazel-materialized dev root under
// .verself/tools/root. The upstream pin (url + sha256 / OCI digest) lives once
// in the Bazel module graph, never restated here.
`

func render(catalog map[string]map[string]string) ([]byte, error) {
	if len(catalog) == 0 {
		return nil, fmt.Errorf("empty catalog")
	}
	names := make([]string, 0, len(catalog))
	for name := range catalog {
		names = append(names, name)
	}
	sort.Strings(names)

	var buf bytes.Buffer
	buf.WriteString(header)
	buf.WriteString("tools: {\n")
	for _, name := range names {
		platforms := catalog[name]
		if len(platforms) == 0 {
			return nil, fmt.Errorf("tool %q has no platforms", name)
		}
		plats := make([]string, 0, len(platforms))
		for p := range platforms {
			plats = append(plats, p)
		}
		sort.Strings(plats)
		fmt.Fprintf(&buf, "\t%s: platforms: {\n", cueField(name))
		for _, p := range plats {
			exe := platforms[p]
			if exe == "" {
				return nil, fmt.Errorf("tool %q platform %q has no executable", name, p)
			}
			fmt.Fprintf(&buf, "\t\t%s: executable: %s\n", cueField(p), cueString(exe))
		}
		buf.WriteString("\t}\n")
	}
	buf.WriteString("}\n")
	return buf.Bytes(), nil
}

// cueField quotes a struct field label only when it is not a bare identifier.
// Names like "linux/amd64" and "stripe-cli-projects" must be quoted.
func cueField(name string) string {
	if isBareIdent(name) {
		return name
	}
	return cueString(name)
}

func cueString(s string) string {
	out, _ := json.Marshal(s)
	return string(out)
}

func isBareIdent(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		switch {
		case r == '_':
		case r >= 'a' && r <= 'z':
		case r >= 'A' && r <= 'Z':
		case r >= '0' && r <= '9' && i > 0:
		default:
			return false
		}
	}
	return true
}
